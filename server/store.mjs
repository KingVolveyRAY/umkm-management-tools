function salesTable(table, updated = false) {
  const additions = updated
    ? 'outlet_id INTEGER NOT NULL DEFAULT 1, ' + orderColumns.map(([key, definition]) => key + ' ' + definition).join(', ') + ','
    : '';
  return `
    CREATE TABLE IF NOT EXISTS ${table} (
      id TEXT PRIMARY KEY, request_id TEXT NOT NULL, employee_id INTEGER NOT NULL REFERENCES users(id),
      method TEXT NOT NULL CHECK (method IN ('cash','qris_static','qris_dynamic')),
      status TEXT NOT NULL CHECK (status IN ('pending','paid','failed')),
      provider TEXT NOT NULL, items TEXT NOT NULL, amount INTEGER NOT NULL CHECK (amount ${updated ? '>= 0' : '> 0'}),
      cash_received INTEGER, qr_value TEXT, qr_url TEXT, provider_status TEXT,
      created_at TEXT NOT NULL, paid_at TEXT, paid_day TEXT,
      ${additions}
      UNIQUE (employee_id, request_id)
    );
  `;
}

export function databaseSchema(postgres = false) {
  const id = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER';
  const real = postgres ? 'DOUBLE PRECISION' : 'REAL';
  return `
    CREATE TABLE IF NOT EXISTS store (
      id INTEGER PRIMARY KEY CHECK (id = 1),
      name TEXT NOT NULL, outlet TEXT NOT NULL, latitude ${real}, longitude ${real},
      radius INTEGER NOT NULL DEFAULT 150, static_qris TEXT,
      mode TEXT NOT NULL CHECK (mode IN ('demo','live'))
    );
    CREATE TABLE IF NOT EXISTS outlets (
      id ${id} PRIMARY KEY,
      name TEXT NOT NULL, outlet TEXT NOT NULL, latitude ${real}, longitude ${real},
      radius INTEGER NOT NULL DEFAULT 150, static_qris TEXT
    );
    CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY);
    CREATE TABLE IF NOT EXISTS users (
      id ${id} PRIMARY KEY, name TEXT NOT NULL,
      username TEXT NOT NULL UNIQUE ${postgres ? '' : 'COLLATE NOCASE'}, password_hash TEXT NOT NULL,
      role TEXT NOT NULL CHECK (role IN ('owner','employee')),
      active INTEGER NOT NULL DEFAULT 1
    );
    CREATE UNIQUE INDEX IF NOT EXISTS users_lower_username ON users (LOWER(username));
    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
      expires_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS products (
      id ${id} PRIMARY KEY, name TEXT NOT NULL, category TEXT NOT NULL,
      price INTEGER NOT NULL CHECK (price > 0), active INTEGER NOT NULL DEFAULT 1
    );
    ${salesTable('sales')}
    CREATE INDEX IF NOT EXISTS sales_paid_day ON sales (paid_day,status);
    CREATE TABLE IF NOT EXISTS attendance (
      id ${id} PRIMARY KEY, employee_id INTEGER NOT NULL REFERENCES users(id),
      kind TEXT NOT NULL CHECK (kind IN ('in','out')), day TEXT NOT NULL,
      timestamp TEXT NOT NULL, latitude ${real} NOT NULL, longitude ${real} NOT NULL,
      accuracy ${real} NOT NULL, distance INTEGER NOT NULL,
      venue_status TEXT NOT NULL CHECK (venue_status IN ('onsite','uncertain','outside')),
      photo ${postgres ? 'BYTEA' : 'BLOB'}, UNIQUE (employee_id,day,kind)
    );
    CREATE TABLE IF NOT EXISTS notices (
      id ${id} PRIMARY KEY, kind TEXT NOT NULL, title TEXT NOT NULL, detail TEXT NOT NULL,
      created_at TEXT NOT NULL, is_read INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS revenue_targets (
      outlet_id INTEGER NOT NULL REFERENCES outlets(id), month TEXT NOT NULL,
      amount BIGINT NOT NULL CHECK (amount >= 0),
      PRIMARY KEY (outlet_id,month)
    );
    CREATE TABLE IF NOT EXISTS attendance_challenges (
      id TEXT PRIMARY KEY, employee_id INTEGER NOT NULL REFERENCES users(id),
      outlet_id INTEGER NOT NULL REFERENCES outlets(id), kind TEXT NOT NULL,
      steps TEXT NOT NULL, issued_at TEXT NOT NULL, expires_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS attendance_challenges_employee ON attendance_challenges (employee_id,kind);
    CREATE TABLE IF NOT EXISTS customers (
      id ${id} PRIMARY KEY, outlet_id INTEGER NOT NULL REFERENCES outlets(id),
      name TEXT NOT NULL, phone TEXT, contact_key TEXT NOT NULL, created_at TEXT NOT NULL,
      UNIQUE (outlet_id,contact_key)
    );
    CREATE TABLE IF NOT EXISTS promotions (
      id ${id} PRIMARY KEY, outlet_id INTEGER NOT NULL REFERENCES outlets(id), name TEXT NOT NULL,
      discount_type TEXT NOT NULL CHECK (discount_type IN ('percent','fixed')),
      value INTEGER NOT NULL CHECK (value > 0), starts_at TEXT NOT NULL, ends_at TEXT NOT NULL,
      active INTEGER NOT NULL DEFAULT 1
    );
    CREATE INDEX IF NOT EXISTS promotions_outlet_schedule ON promotions (outlet_id,active,starts_at,ends_at);
  `;
}

