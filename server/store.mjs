export const migrateFirstOutlet = `
  INSERT INTO outlets (id,name,outlet,latitude,longitude,radius,static_qris)
  SELECT id,name,outlet,latitude,longitude,radius,static_qris FROM store WHERE id = 1
  ON CONFLICT (id) DO NOTHING
`;

export const outletIndexes = `
  CREATE INDEX IF NOT EXISTS sales_outlet_day ON sales (outlet_id,status,paid_day);
  CREATE INDEX IF NOT EXISTS attendance_outlet_day ON attendance (outlet_id,day);
  CREATE INDEX IF NOT EXISTS notices_outlet_time ON notices (outlet_id,created_at);
  CREATE INDEX IF NOT EXISTS products_outlet ON products (outlet_id,active,id);
  CREATE INDEX IF NOT EXISTS users_outlet_role ON users (outlet_id,role,active);
`;

export function commerceMigration(postgres) {
  const oldColumns = 'id,request_id,employee_id,method,status,provider,items,amount,cash_received,qr_value,qr_url,provider_status,created_at,paid_at,paid_day,outlet_id';
  const updateSales = postgres ? `
    ${orderColumns.map(([column, definition]) => 'ALTER TABLE sales ADD COLUMN ' + column + ' ' + definition + ';').join('\n')}
    ALTER TABLE sales DROP CONSTRAINT sales_amount_check;
    ALTER TABLE sales ADD CONSTRAINT sales_amount_check CHECK (amount >= 0);
  ` : `
    ${salesTable('sales_updated', true)}
    INSERT INTO sales_updated (${oldColumns}) SELECT ${oldColumns} FROM sales;
    DROP TABLE sales;
    ALTER TABLE sales_updated RENAME TO sales;
    CREATE INDEX IF NOT EXISTS sales_paid_day ON sales (paid_day,status);
    CREATE INDEX IF NOT EXISTS sales_outlet_day ON sales (outlet_id,status,paid_day);
  `;
  return `
    ALTER TABLE outlets ADD COLUMN address TEXT NOT NULL DEFAULT '';
    ${updateSales}
    CREATE INDEX IF NOT EXISTS sales_customer ON sales (outlet_id,customer_id,status,paid_at);
    INSERT INTO schema_migrations VALUES (2);
  `;
}

export function verifyMode(existing) {
  if (existing && existing.mode !== 'live') {
    throw new Error('Basis data demo tidak didukung. Gunakan basis data operasional.');
  }
}

export function initialRows({ ownerUsername, ownerPassword } = {}) {
  if (!/^[a-z0-9._-]{3,40}$/i.test(ownerUsername ?? '') || (ownerPassword ?? '').length < 12 || ownerPassword.length > 128) {
    throw new Error('Inisialisasi operasional membutuhkan OWNER_USERNAME dan OWNER_PASSWORD (12–128 karakter).');
  }
  return [
    insertRows('store', 'id,name,outlet,mode', [[1, 'Usaha saya', 'Outlet utama', 'live']]),
    insertRows('users', 'name,username,password_hash,role', [['Pemilik', ownerUsername, hashPassword(ownerPassword), 'owner']]),
  ];
}

function insertRows(table, columns, rows) {
  const row = '(' + rows[0].map(() => '?').join(',') + ')';
  return [`INSERT INTO ${table} (${columns}) VALUES ` + rows.map(() => row).join(','), rows.flat()];
}

export function openStore(path, options) {
  if (path !== ':memory:') mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  const db = new DatabaseSync(path);
  try {
    db.exec('PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL; PRAGMA busy_timeout = 5000;');
    transaction(db, () => {
      db.exec(databaseSchema());
      const existing = db.prepare('SELECT mode FROM store WHERE id = 1').get();
      verifyMode(existing);
      if (!existing) {
        for (const [sql, args] of initialRows(options)) db.prepare(sql).run(...args);
      }
      if (!db.prepare('SELECT version FROM schema_migrations WHERE version = 1').get()) {
        db.exec(migrateFirstOutlet);
        for (const [table, column, definition] of outletMigrationColumns) {
          const columns = db.prepare('PRAGMA table_info(' + table + ')').all();
          if (!columns.some(entry => entry.name === column)) {
            db.exec('ALTER TABLE ' + table + ' ADD COLUMN ' + column + ' ' + definition);
          }
        }
        db.exec(outletIndexes);
        db.exec('INSERT INTO schema_migrations VALUES (1)');
      }
      if (!db.prepare('SELECT version FROM schema_migrations WHERE version = 2').get()) {
        db.exec(commerceMigration(false));
      }
    });
    return db;
  } catch (error) {
    db.close();
    throw error;
  }
}

export function venueLocation(store, latitude, longitude, accuracy) {
  const rad = Math.PI / 180;
  const north = (latitude - store.latitude) * rad;
  const east = (longitude - store.longitude) * rad;
  const haversine = Math.sin(north / 2) ** 2
    + Math.cos(store.latitude * rad) * Math.cos(latitude * rad) * Math.sin(east / 2) ** 2;
  const meters = 6371000 * 2 * Math.asin(Math.sqrt(Math.min(1, haversine)));
  const venue_status = meters + accuracy <= store.radius ? 'onsite'
    : meters - accuracy > store.radius ? 'outside' : 'uncertain';
  return { distance: Math.round(meters), venue_status };
}
